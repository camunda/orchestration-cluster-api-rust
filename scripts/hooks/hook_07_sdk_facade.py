"""Hook 07 — full-surface ergonomic facade.

The sibling SDKs (JS, Python, C#) expose a *flat* client with one ergonomic method per
REST operation, each routed through the shared auth / retry / backpressure machinery. In
JS and C# that facade is itself *generated* from the operation list — we do the same here.

This hook parses the generated low-level operation functions in
``client/src/apis/*_api.rs`` (each uniformly shaped as
``pub async fn op(configuration: &Configuration, params: OpParams) -> Result<T, Error<E>>``)
and emits ``src/runtime/facade_generated.rs``: an ``impl CamundaClient`` block with one
method per operation that

  * builds an authenticated ``Configuration`` via ``self.configuration()``,
  * runs the call under ``self.guarded(..)`` (adaptive backpressure + transient retry), and
  * maps the typed ``Error<E>`` to :class:`CamundaError` via the blanket ``From`` impl.

Operations already covered by a hand-written, more-ergonomic curated method (semantic
keys, typed variables, default-tenant injection, deploy-from-file) are skipped so the
nicer versions win — see ``CURATED_SKIP``.

Default-tenant injection is derived from the bundler's ``spec-metadata.json``, not a
list: every generated operation whose JSON request body (or a ``oneOf``/``anyOf`` variant
of it) is listed in ``optionalTenantIdInBodyVariants`` gets an ``inject_default_tenant_<op>`` helper that
fills the effective default tenant (configured ``CAMUNDA_TENANT_ID`` or ``<default>``)
when the caller left it unset, on that variant only — mirroring the Camunda Java client.

Operations whose body carries an optional ``tenantIds`` list plus a ``tenantFilter``
(``optionalTenantIdsInBody``, e.g. ``activateProbes``) get an
``inject_default_tenant_ids_<op>`` helper instead, which applies the same rule as the curated
``activate_jobs`` through ``apply_default_tenant_ids``: with no ids, and a filter other than
``ASSIGNED``, send ``[<effective default tenant>]``. ``activate_jobs`` keeps its curated wrapper.
"""

from __future__ import annotations

import re
from pathlib import Path

from .common import Context, snake_case

NUMBER = 7
NAME = "sdk-facade"

# Generated operation function names that collide with — or are superseded by — a
# hand-written curated method on `CamundaClient`. These are intentionally NOT generated.
CURATED_SKIP = {
    # name collisions with curated ergonomic wrappers (would be duplicate methods)
    "activate_jobs",
    "broadcast_signal",
    "cancel_process_instance",
    "complete_job",
    "correlate_message",
    "create_process_instance",
    "evaluate_decision",
    "fail_job",
    "get_process_instance",
    "publish_message",
    "search_variables",
    "throw_job_error",
    # superseded by the curated `topology()` wrapper
    "get_topology",
    # superseded by curated wrappers that inject the configured default tenant id
    # (CAMUNDA_TENANT_ID) into the request, which the plain generated facade does not
    "create_deployment",
    "evaluate_conditionals",
    "evaluate_expression",
    # non-idempotent: a relative clock offset must not be auto-retried on an unknown
    # outcome (a lost 5xx/network response would double-apply it), so it gets a curated
    # wrapper that runs under backpressure WITHOUT the transient-retry policy.
    "add_clock",
}

# Matches each generated operation. `params` group is optional (6 ops take no params).
# Tolerant of both rustfmt-formatted output (trailing commas, newlines) and the raw
# openapi-generator output (single line, no trailing commas) — postprocess runs BEFORE
# `cargo fmt`, so we must parse the unformatted form.
_OP_RE = re.compile(
    r"pub async fn (\w+)\(\s*"
    r"configuration: &configuration::Configuration"
    r"(?:\s*,\s*params:\s*(\w+))?"
    r"\s*,?\s*\)\s*->\s*Result<(.*?),\s*Error<",
    re.DOTALL,
)

HEADER = """\
// @generated by scripts/postprocess.py (hook 07) — DO NOT EDIT.
//
// Full-surface ergonomic facade: one method per REST operation, mirroring the flat
// clients of the JS / Python / C# SDKs. Every method builds an authenticated
// `Configuration`, runs the call under the adaptive backpressure gate + transient retry
// policy (`guarded`), and maps the typed low-level error to `CamundaError`.
//
// Operations with a hand-written, more-ergonomic curated wrapper (semantic keys, typed
// variables, default-tenant injection) are implemented in `client.rs` instead.

#![allow(clippy::too_many_lines)]
#![allow(deprecated)]

use crate::{CamundaClient, Result};
use camunda_orchestration_api_client::models;
"""


def _resolve(schema: dict, schemas: dict) -> tuple[str | None, dict]:
    name = None
    seen: set[str] = set()
    while isinstance(schema, dict) and "$ref" in schema:
        name = schema["$ref"].split("/")[-1]
        if name in seen:
            break
        seen.add(name)
        schema = schemas.get(name) or {}
    return name, schema or {}


def build_tenant_injection_map(spec: dict, metadata: dict | None) -> dict[str, dict]:
    """snake_case(operationId) -> {"schema": body schema name, "variants": [names] | None}.

    The selection comes from ``camunda-schema-bundler``'s ``spec-metadata.json``
    (``optionalTenantIdInBodyVariants``), so the SDK does not re-walk the spec for it.
    ``variants`` is None for a plain body schema with an optional top-level ``tenantId``;
    otherwise it lists the union variants that carry one (others get nothing).
    """
    if not metadata or "operations" not in metadata:
        raise SystemExit("hook 07: spec-metadata.json with `operations` is required")
    schemas = (spec.get("components") or {}).get("schemas") or {}
    out: dict[str, dict] = {}
    for op in metadata["operations"]:
        if "optionalTenantIdInBodyVariants" not in op:
            raise SystemExit(
                f"hook 07: {op.get('operationId')} lacks optionalTenantIdInBodyVariants; "
                "re-bundle with camunda-schema-bundler >= 2.5.1"
            )
        variants = op["optionalTenantIdInBodyVariants"]
        if not variants:
            continue
        op_id = op["operationId"]
        item = (spec.get("paths") or {}).get(op["path"]) or {}
        body = (((item.get(op["method"]) or {}).get("requestBody") or {}).get("content") or {})
        body = (body.get("application/json") or {}).get("schema")
        if not body:
            raise SystemExit(f"hook 07: {op_id} has tenant variants but no JSON body")
        name, resolved = _resolve(body, schemas)
        if resolved.get("oneOf") or resolved.get("anyOf"):
            out[snake_case(op_id)] = {"schema": name, "variants": list(variants)}
        else:
            if variants != [name]:
                raise SystemExit(f"hook 07: {op_id} variants {variants} != body schema {name}")
            out[snake_case(op_id)] = {"schema": name, "variants": None}
    return out


def build_tenant_ids_injection_map(spec: dict, metadata: dict | None) -> dict[str, dict]:
    """snake_case(operationId) -> {"schema": body schema name} for ``optionalTenantIdsInBody`` ops.

    Like :func:`build_tenant_injection_map`, the selection comes from the bundler's
    ``spec-metadata.json`` rather than a list. Curated operations (``CURATED_SKIP``) are left
    to their hand-written wrapper, so only a genuinely new one is picked up here.
    """
    if not metadata or "operations" not in metadata:
        raise SystemExit("hook 07: spec-metadata.json with `operations` is required")
    schemas = (spec.get("components") or {}).get("schemas") or {}
    out: dict[str, dict] = {}
    for op in metadata["operations"]:
        if "optionalTenantIdsInBody" not in op:
            raise SystemExit(
                f"hook 07: {op.get('operationId')} lacks optionalTenantIdsInBody; "
                "re-bundle with camunda-schema-bundler >= 2.5.1"
            )
        if not op["optionalTenantIdsInBody"]:
            continue
        op_id = op["operationId"]
        fn = snake_case(op_id)
        if fn in CURATED_SKIP:
            continue
        if op.get("optionalTenantIdInBody") or op.get("optionalTenantIdInBodyVariants"):
            raise SystemExit(
                f"hook 07: {op_id} has both tenantId and tenantIds in its body; "
                "this hook injects only one of them"
            )
        item = (spec.get("paths") or {}).get(op["path"]) or {}
        body = (((item.get(op["method"]) or {}).get("requestBody") or {}).get("content") or {})
        body = (body.get("application/json") or {}).get("schema")
        if not body:
            raise SystemExit(f"hook 07: {op_id} has optional tenantIds but no JSON body")
        name, _ = _resolve(body, schemas)
        if not name:
            raise SystemExit(f"hook 07: {op_id} body is not a named schema")
        out[fn] = {"schema": name}
    return out


def _params_body_field(text: str, params: str, schema: str) -> tuple[str, bool]:
    """Find the field of ``params`` typed as ``models::<schema>``; returns (name, optional)."""
    m = re.search(r"pub struct " + re.escape(params) + r"\s*\{(.*?)\}", text, re.DOTALL)
    if not m:
        raise SystemExit(f"hook 07: params struct {params} not found")
    for fm in re.finditer(r"pub (\w+)\s*:\s*([^,]+?)\s*(?:,|$)", m.group(1)):
        ty = re.sub(r"\s+", "", fm.group(2))
        if ty == f"models::{schema}":
            return fm.group(1), False
        if ty == f"Option<models::{schema}>":
            return fm.group(1), True
    raise SystemExit(f"hook 07: no models::{schema} body field on {params}")



def _build_doc_map(ctx: Context) -> dict[str, dict]:
    """Map snake_case(operationId) -> {method, path, summary} from the spec, so each
    generated method gets a meaningful doc comment."""
    out: dict[str, dict] = {}
    for path, item in (ctx.spec.get("paths") or {}).items():
        if not isinstance(item, dict):
            continue
        for method, op in item.items():
            if method.lower() not in {
                "get", "post", "put", "patch", "delete", "head", "options",
            }:
                continue
            if not isinstance(op, dict):
                continue
            op_id = op.get("operationId")
            if not op_id:
                continue
            out[snake_case(op_id)] = {
                "method": method.upper(),
                "path": path,
                "summary": (op.get("summary") or op.get("description") or "").strip(),
            }
    return out


def _parse_operations(apis_dir: Path) -> list[dict]:
    ops: list[dict] = []
    for f in sorted(apis_dir.glob("*_api.rs")):
        module = f.stem
        text = f.read_text(encoding="utf-8")
        for m in _OP_RE.finditer(text):
            ops.append(
                {
                    "module": module,
                    "fn": m.group(1),
                    "params": m.group(2),  # ParamsType name or None
                    "ret": m.group(3).strip(),
                    "text": text,
                }
            )
    return ops


def _first_sentence(text: str) -> str:
    text = " ".join(text.split())
    # Keep doc comments single-line and tidy.
    for sep in (". ", "\n"):
        if sep in text:
            text = text.split(sep, 1)[0]
            break
    return text.rstrip(".")


def _render_injector(op: dict, inj: dict) -> str:
    module, fn, params = op["module"], op["fn"], op["params"]
    if not params:
        raise SystemExit(f"hook 07: {fn} has a tenant-scoped body but no params")
    field, optional = _params_body_field(op["text"], params, inj["schema"])
    params_ty = f"camunda_orchestration_api_client::apis::{module}::{params}"
    body = f"params.{field}"
    lines = [
        f"/// Apply the effective default tenant to `{fn}` when the body leaves `tenantId` unset.",
        f"pub(crate) fn inject_default_tenant_{fn}(",
        f"    mut params: {params_ty},",
        "    config: &CamundaConfig,",
        f") -> {params_ty} {{",
    ]
    if inj["variants"] is None:
        target = f"params.{field}"
        if optional:
            lines.append(f"    if let Some(b) = {body}.as_mut() {{")
            lines.append("        b.tenant_id = apply_default_tenant(b.tenant_id.take(), config);")
            lines.append("    }")
        else:
            lines.append(f"    {target}.tenant_id = apply_default_tenant({target}.tenant_id.take(), config);")
    else:
        for v in inj["variants"]:
            pat = f"models::{inj['schema']}::{v}(b)"
            if optional:
                pat = f"Some({pat})"
            lines.append(f"    if let {pat} = &mut {body} {{")
            lines.append("        b.tenant_id = apply_default_tenant(b.tenant_id.take(), config);")
            lines.append("    }")
    lines.append("    params")
    lines.append("}")
    return "\n".join(lines)


def _render_tenant_ids_injector(op: dict, inj: dict, model_text: str) -> str:
    module, fn, params = op["module"], op["fn"], op["params"]
    if not params:
        raise SystemExit(f"hook 07: {fn} has a tenant-scoped body but no params")
    # Fail the run, rather than emit a call that cannot compile or silently does nothing, when the
    # generated model is not the shape the shared helper expects.
    for field in ("tenant_ids", "tenant_filter"):
        if not re.search(r"pub " + field + r"\s*:", model_text):
            raise SystemExit(f"hook 07: models::{inj['schema']} has no `{field}` field for {fn}")
    field, optional = _params_body_field(op["text"], params, inj["schema"])
    params_ty = f"camunda_orchestration_api_client::apis::{module}::{params}"
    lines = [
        f"/// Apply the effective default tenant to `{fn}` when the body names no tenant ids.",
        f"pub(crate) fn inject_default_tenant_ids_{fn}(",
        f"    mut params: {params_ty},",
        "    config: &CamundaConfig,",
        f") -> {params_ty} {{",
    ]
    target = f"params.{field}"
    if optional:
        lines.append(f"    if let Some(b) = {target}.as_mut() {{")
        lines.append("        apply_default_tenant_ids(b.tenant_filter, &mut b.tenant_ids, config);")
        lines.append("    }")
    else:
        lines.append(
            f"    apply_default_tenant_ids({target}.tenant_filter, &mut {target}.tenant_ids, config);"
        )
    lines.append("    params")
    lines.append("}")
    return "\n".join(lines)


def _render_method(op: dict, doc: dict | None, injector: str | None = None) -> str:
    module, fn, params, ret = op["module"], op["fn"], op["params"], op["ret"]
    call_path = f"camunda_orchestration_api_client::apis::{module}::{fn}"

    lines: list[str] = []
    if doc and (doc.get("summary") or doc.get("path")):
        summary = _first_sentence(doc.get("summary") or "")
        ref = f"`{doc['method']} {doc['path']}`" if doc.get("path") else ""
        if summary and ref:
            lines.append(f"    /// {summary} ({ref}).")
        elif summary:
            lines.append(f"    /// {summary}.")
        elif ref:
            lines.append(f"    /// {ref}.")
    else:
        lines.append(f"    /// Generated facade for `{module}::{fn}`.")

    if params:
        params_ty = f"camunda_orchestration_api_client::apis::{module}::{params}"
        lines.append(f"    pub async fn {fn}(&self, params: {params_ty}) -> Result<{ret}> {{")
        if injector:
            lines.append(f"        let params = {injector}_{fn}(params, self.config());")
        lines.append("        self.guarded(|| {")
        lines.append("            let params = params.clone();")
        lines.append("            async move {")
        lines.append("                let cfg = self.configuration().await?;")
        lines.append(f"                Ok({call_path}(&cfg, params).await?)")
        lines.append("            }")
        lines.append("        })")
        lines.append("        .await")
        lines.append("    }")
    else:
        lines.append(f"    pub async fn {fn}(&self) -> Result<{ret}> {{")
        lines.append("        self.guarded(|| async {")
        lines.append("            let cfg = self.configuration().await?;")
        lines.append(f"            Ok({call_path}(&cfg).await?)")
        lines.append("        })")
        lines.append("        .await")
        lines.append("    }")
    return "\n".join(lines)


def run(ctx: Context) -> None:
    apis_dir = ctx.client_dir / "src" / "apis"
    if not apis_dir.is_dir():
        ctx.log(NAME, f"WARNING: {apis_dir} not found; skipping facade generation")
        return

    sdk_root = ctx.client_dir.parent
    out_path = sdk_root / "src" / "runtime" / "facade_generated.rs"

    doc_map = _build_doc_map(ctx)
    ops = _parse_operations(apis_dir)

    tenant_map = build_tenant_injection_map(ctx.spec, ctx.metadata)
    tenant_ids_map = build_tenant_ids_injection_map(ctx.spec, ctx.metadata)

    generated, injectors, skipped = [], [], 0
    uses_tenant, uses_tenant_ids = False, False
    for op in sorted(ops, key=lambda o: (o["module"], o["fn"])):
        if op["fn"] in CURATED_SKIP:
            skipped += 1
            continue
        inj = tenant_map.get(op["fn"])
        ids_inj = tenant_ids_map.get(op["fn"])
        injector = None
        if inj:
            injectors.append(_render_injector(op, inj))
            injector, uses_tenant = "inject_default_tenant", True
        elif ids_inj:
            model = ctx.client_dir / "src" / "models" / f"{snake_case(ids_inj['schema'])}.rs"
            if not model.is_file():
                raise SystemExit(f"hook 07: model file {model} for {op['fn']} not found")
            injectors.append(
                _render_tenant_ids_injector(op, ids_inj, model.read_text(encoding="utf-8"))
            )
            injector, uses_tenant_ids = "inject_default_tenant_ids", True
        generated.append(_render_method(op, doc_map.get(op["fn"]), injector=injector))

    header = HEADER
    if injectors:
        imports = []
        if uses_tenant:
            imports.append("use super::client::apply_default_tenant;")
        if uses_tenant_ids:
            imports.append("use super::client::apply_default_tenant_ids;")
        imports.append("use super::config::CamundaConfig;")
        header = header.replace(
            "use crate::{CamundaClient, Result};",
            "\n".join(imports) + "\nuse crate::{CamundaClient, Result};",
        )
    body = header + "\nimpl CamundaClient {\n" + "\n\n".join(generated) + "\n}\n"
    if injectors:
        body += "\n" + "\n\n".join(injectors) + "\n"
    out_path.write_text(body, encoding="utf-8")

    ctx.log(
        NAME,
        f"wrote {out_path.relative_to(sdk_root)}: "
        f"{len(generated)} generated method(s), {skipped} curated skip(s)",
    )
